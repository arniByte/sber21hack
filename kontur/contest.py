"""Appendix B metrics and a local audit of normalized Cassandra executions.

This is a Kontur import contract. Map organizer exports to it once their schema
is available. Use UTF-8 CSV with a comma delimiter and offset-aware timestamps.

Fills: team_id,execution_id,situation_id,timestamp,symbol,side,quantity,price,commission,costs
Marks: team_id,timestamp,equity,positions_json

Quantity is in shares. A situation_id groups partial BUY and SELL executions
generated by one signal for one symbol. Additional costs exclude commission
and any price impact already in price. Supply real fills only to the audit.

Marks describe the portfolio after all fills at each timestamp. Use {} when
flat, otherwise e.g. {"SBER":{"quantity":10,"mark_price":300.15}}. Preserve the
initial flat mark before the first fill, all available intermediate marks, and
a final mark at or after the last fill. Quote positions_json as a CSV field.
Only cash equities in RUB, a 35,000 ₽ initial balance, and no deposits,
withdrawals, shorts, margin, or other cash flows are supported by this replay.
"""

import csv
from dataclasses import dataclass, field
from datetime import datetime
from decimal import Decimal, InvalidOperation
import json
import math
from zoneinfo import ZoneInfo


CAPITAL = 35_000
STRATEGY_CHECKS = (
    "entry_exit_rules",
    "position_and_risk",
    "signal_logic",
    "ml_evidence",
    "test_evidence",
)
FILL_COLUMNS = (
    "team_id", "execution_id", "situation_id", "timestamp", "symbol", "side",
    "quantity", "price", "commission", "costs",
)
MARK_COLUMNS = ("team_id", "timestamp", "equity", "positions_json")
MOSCOW = ZoneInfo("Europe/Moscow")
KOPECK = Decimal("0.01")


def drawdown_score(max_drawdown_pct):
    if not math.isfinite(max_drawdown_pct) or max_drawdown_pct < 0:
        raise ValueError("Просадка должна быть конечным неотрицательным процентом")
    for threshold, points in ((2, 25), (4, 20), (6, 15), (8, 10), (10, 5)):
        if max_drawdown_pct <= threshold:
            return points
    return 0


def profit_factor_score(pf, no_losses=False):
    if pf is None:
        return 15 if no_losses else 0
    if not math.isfinite(pf) or pf < 0:
        raise ValueError("Profit Factor должен быть конечным неотрицательным числом")
    if no_losses:
        raise ValueError("При отсутствии убытков используйте Profit Factor = null")
    if pf >= 1.50:
        return 15
    if pf >= 1.20:
        return 10
    return 5 if pf >= 1 else 0


def contest_scores(metrics, actual_situations=0, actual_days=0,
                   validated_holdout_situations=0, best_positive_return_pct=None,
                   strategy_checks=None):
    """Compute a scenario or preliminary audit, never an organizer's result.

    A positive leader return is required to score a positive strategy return.
    Historical counts may be provided only after validation on untouched real
    market data. Strategy checks are self-assessment until jury confirmation.
    """
    for count in (actual_situations, actual_days, validated_holdout_situations):
        if type(count) is not int or count < 0:
            raise ValueError("Число ситуаций и торговых дней должно быть целым и неотрицательным")

    return_pct = metrics["net_pnl"] / CAPITAL * 100
    if not math.isfinite(return_pct):
        raise ValueError("Чистый результат должен быть конечным числом")
    if best_positive_return_pct is not None:
        if not math.isfinite(best_positive_return_pct) or best_positive_return_pct < 0:
            raise ValueError("Доходность лидера должна быть конечным неотрицательным процентом")
        if return_pct > best_positive_return_pct and not math.isclose(return_pct, best_positive_return_pct):
            raise ValueError("Доходность стратегии превышает указанную доходность лидера")
    financial_result = None
    if return_pct <= 0:
        financial_result = 0
    elif best_positive_return_pct:
        financial_result = 40 * min(1, return_pct / best_positive_return_pct)

    repeatability = 0
    if actual_situations >= 2:
        repeatability = 5
        if (actual_situations >= 5 and actual_days >= 3) or validated_holdout_situations >= 30:
            repeatability = 10

    quality = None
    if strategy_checks is not None:
        if set(strategy_checks) - set(STRATEGY_CHECKS) or any(
            type(value) is not bool for value in strategy_checks.values()
        ):
            raise ValueError("Неизвестный пункт чек-листа или некорректное значение")
        if all(key in strategy_checks for key in STRATEGY_CHECKS):
            quality = 2 * sum(strategy_checks.values())

    is_actual = metrics.get("origin") == "execution_audit"
    has_activity = is_actual or metrics.get("trade_count", 1) > 0
    components = {
        "financial_result": financial_result,
        "drawdown": drawdown_score(metrics["max_drawdown_pct"]) if has_activity else None,
        "profit_factor": profit_factor_score(metrics.get("profit_factor"), metrics.get("no_losses", False)),
        "repeatability": repeatability,
        "strategy_quality": quality,
    }
    concentration = metrics.get("concentration_pct")
    concentration_review = concentration is not None and concentration > 60
    known_points = sum(value for value in components.values() if value is not None)
    return {
        "status": "preliminary_execution_audit" if is_actual else "backtest_only",
        "capital": CAPITAL,
        "return_pct": return_pct,
        "components": components,
        "total": known_points if is_actual and None not in components.values() else None,
        "known_points": known_points,
        "concentration_review": concentration_review,
        "actual_situations": actual_situations,
        "actual_days": actual_days,
        "validated_holdout_situations": validated_holdout_situations,
    }


def _read_rows(path, columns):
    with open(path, encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle, strict=True)
        names = reader.fieldnames or []
        if len(names) != len(set(names)) or set(names) != set(columns):
            raise ValueError(f"{path}: ожидаются столбцы {','.join(columns)}")
        rows = []
        for row in reader:
            if None in row or any(value is None or not value.strip() for value in row.values()):
                raise ValueError(f"{path}, строка {reader.line_num}: пропущено или добавлено поле")
            rows.append({key: value.strip() for key, value in row.items()})
        return rows


def _timestamp(value):
    moment = datetime.fromisoformat(value)
    if moment.tzinfo is None:
        raise ValueError(f"Укажите смещение часового пояса для {value}")
    return moment.astimezone(MOSCOW)


def _number(value, context):
    try:
        number = Decimal(str(value))
        if not math.isfinite(float(number)) or number < 0:
            raise ValueError
    except (InvalidOperation, OverflowError, ValueError) as exc:
        raise ValueError(f"{context}: ожидается конечное неотрицательное число") from exc
    return number


def _quantity(value, context):
    number = _number(value, context)
    if number == 0 or number != number.to_integral_value():
        raise ValueError(f"{context}: количество должно быть положительным целым")
    return int(number)


def _unique_object(pairs):
    result = dict(pairs)
    if len(result) != len(pairs):
        raise ValueError("positions_json содержит повторяющиеся ключи")
    return result


@dataclass
class _Situation:
    symbol: str
    opened_at: datetime
    quantity: int = 0
    balance: Decimal = Decimal(0)
    costs: Decimal = Decimal(0)
    closed_at: datetime | None = None
    execution_ids: list[str] = field(default_factory=list)

    def record(self, row):
        if self.symbol != row["symbol"] or self.closed_at is not None:
            raise ValueError(f"Некорректное повторное использование ситуации {row['situation_id']}")
        side = row["side"]
        if side not in {"BUY", "SELL"}:
            raise ValueError("Направление сделки должно быть BUY или SELL")
        quantity = _quantity(row["quantity"], row["execution_id"])
        signed_quantity = quantity if side == "BUY" else -quantity
        if self.quantity + signed_quantity < 0:
            raise ValueError(f"Продажа превышает позицию в ситуации {row['situation_id']}")
        price = _number(row["price"], row["execution_id"])
        if price == 0:
            raise ValueError("Цена исполнения должна быть положительной")
        costs = _number(row["commission"], row["execution_id"]) + _number(row["costs"], row["execution_id"])
        flow = -signed_quantity * price - costs
        self.quantity += signed_quantity
        self.balance += flow
        self.costs += costs
        self.execution_ids.append(row["execution_id"])
        if self.quantity == 0:
            self.closed_at = row["timestamp"]
        return flow, signed_quantity

    def to_dict(self, identifier):
        return {
            "id": identifier,
            "symbol": self.symbol,
            "opened_at": self.opened_at.isoformat(),
            "closed_at": self.closed_at.isoformat() if self.closed_at else None,
            "open_quantity": self.quantity,
            "net_pnl": float(self.balance) if self.closed_at else None,
            "costs": float(self.costs),
            "execution_ids": self.execution_ids,
        }


def _mark_value(mark, open_positions):
    declared = json.loads(mark["positions_json"], parse_float=Decimal, object_pairs_hook=_unique_object)
    if not isinstance(declared, dict) or set(declared) != set(open_positions):
        raise ValueError(f"Состав позиций не совпадает с исполнениями на {mark['timestamp']}")
    value = Decimal(0)
    for symbol, position in declared.items():
        if not isinstance(position, dict) or set(position) != {"quantity", "mark_price"}:
            raise ValueError(f"Для {symbol} нужны quantity и mark_price")
        quantity = _quantity(position["quantity"], symbol)
        price = _number(position["mark_price"], symbol)
        if quantity != open_positions[symbol] or price == 0:
            raise ValueError(f"Некорректная оценка позиции {symbol} на {mark['timestamp']}")
        value += quantity * price
    return value


def audit_executions(fills_path, equity_path, team_id=None):
    """Replay normalized execution CSVs and verify sampled portfolio marks."""
    fills = _read_rows(fills_path, FILL_COLUMNS)
    marks = _read_rows(equity_path, MARK_COLUMNS)
    teams = {row["team_id"] for row in fills + marks}
    if team_id is None:
        if len(teams) != 1:
            raise ValueError("Укажите ID команды при наличии нескольких команд; выгрузки не должны быть пустыми")
        team_id = teams.pop()
    fills = [row for row in fills if row["team_id"] == team_id]
    marks = [row for row in marks if row["team_id"] == team_id]
    for row in fills + marks:
        row["timestamp"] = _timestamp(row["timestamp"])
    fills.sort(key=lambda row: row["timestamp"])
    marks.sort(key=lambda row: row["timestamp"])
    if len(marks) < 2 or len({mark["timestamp"] for mark in marks}) != len(marks):
        raise ValueError("Требуются минимум две отметки портфеля с разными временами")
    if len({row["execution_id"] for row in fills}) != len(fills):
        raise ValueError("Найдены повторяющиеся ID исполнений")
    if fills and not marks[0]["timestamp"] < fills[0]["timestamp"] <= fills[-1]["timestamp"] <= marks[-1]["timestamp"]:
        raise ValueError("Отметки должны охватывать все исполнения и начинаться до первого исполнения")

    cash, peak = Decimal(CAPITAL), Decimal(CAPITAL)
    open_positions, situations = {}, {}
    equity = []
    next_fill = 0
    for mark in marks:
        while next_fill < len(fills) and fills[next_fill]["timestamp"] <= mark["timestamp"]:
            row = fills[next_fill]
            symbol = row["symbol"]
            situation = situations.setdefault(row["situation_id"], _Situation(symbol, row["timestamp"]))
            flow, quantity = situation.record(row)
            cash += flow
            if cash < 0:
                raise ValueError(f"Отрицательный денежный остаток после исполнения {row['execution_id']}")
            open_positions[symbol] = open_positions.get(symbol, 0) + quantity
            if open_positions[symbol] == 0:
                del open_positions[symbol]
            next_fill += 1

        value = cash + _mark_value(mark, open_positions)
        if abs(value - _number(mark["equity"], "equity")) > KOPECK:
            raise ValueError(f"Стоимость портфеля не совпадает с пересчётом на {mark['timestamp']}")
        peak = max(peak, value)
        equity.append({
            "timestamp": mark["timestamp"].isoformat(),
            "equity": float(value),
            "drawdown_pct": float((peak - value) / peak * 100),
            "open_positions": dict(open_positions),
        })

    closed = {key: item for key, item in situations.items() if item.closed_at is not None}
    pnl = [item.balance for item in closed.values()]
    gross_profit = sum((value for value in pnl if value > 0), Decimal(0))
    gross_loss = -sum((value for value in pnl if value < 0), Decimal(0))
    net = value - CAPITAL
    return {
        "team_id": team_id,
        "start": equity[0]["timestamp"],
        "end": equity[-1]["timestamp"],
        "metrics": {
            "origin": "execution_audit",
            "net_pnl": float(net),
            "return_pct": float(net / CAPITAL * 100),
            "max_drawdown_pct": max(point["drawdown_pct"] for point in equity),
            "profit_factor": float(gross_profit / gross_loss) if gross_loss else None,
            "no_losses": gross_profit > 0 and gross_loss == 0,
            "expectancy": float(sum(pnl) / len(pnl)) if pnl else None,
            "trade_count": len(closed),
            "trade_days": len({item.opened_at.date() for item in closed.values()}),
            "concentration_pct": float(max(pnl) / net * 100) if net > 0 and gross_profit else None,
            "closed_pnl": float(sum(pnl)),
            "open_pnl": float(net - sum(pnl)),
        },
        "equity": equity,
        "situations": [item.to_dict(key) for key, item in closed.items()],
        "open_situations": [item.to_dict(key) for key, item in situations.items() if key not in closed],
        "limitations": [
            "Просадка рассчитана по предоставленным отметкам и может пропустить промежуточный минимум.",
            "Profit Factor и повторяемость рассчитаны по полностью закрытым ситуациям.",
            "Торговые дни считаются по дате первого исполнения каждой закрытой ситуации в Москве.",
            "Формат импорта локальный; официальную выгрузку и баллы подтверждают организаторы.",
        ],
    }
